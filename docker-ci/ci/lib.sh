##
# Tears down a compose project with a podman fallback. `docker compose down`
# fails on rootless podman when killing the slirp4netns network process
# ("rootless netns: kill network process: permission denied"); the containers
# stop but the project's network is orphaned. This runs the plain down and,
# when it errors, finishes the job via the podman CLI (container + network
# cleanup) so a relaunch on the same profile starts clean.
#
# @param ... $@ compose invocation args, i.e. the _launchLine files plus -p <project>
# @author Kevin Guanche Darias
##
function owgeComposeDown () {
        if docker compose "$@" down --remove-orphans 2> /dev/null; then
                return 0;
        fi
        # Fall back to the podman CLI for the netns-kill bug.
        if [ "${_OWGE_RUNTIME-docker}" = "podman" ]; then
                _project_name="";
                _expect_project=0;
                for _a in "$@"; do
                        if [ "$_expect_project" = "1" ]; then
                                _project_name="$_a";
                                _expect_project=0;
                        fi
                        [ "$_a" = "-p" ] && _expect_project=1;
                done
                log warning "compose down failed; cleaning project ${_project_name-<unnamed>} via podman CLI";
                [ -n "$_project_name" ] && podman container rm -f --filter "label=com.docker.compose.project=$_project_name" 2> /dev/null;
                [ -n "$_project_name" ] && podman network rm "${_project_name}_default" 2> /dev/null;
        fi
        return 0;
}

##
# Returns with error if mysql query fails (empty result)
#
# @param string $1 The query to run
# @param string $2 extra filter
#
##
function check_mysql_query_fails() {
	_extra_filter="${2-cat}";
	test `mysql_run "$1" | $_extra_filter | wc -l` -eq 0;
}

