##
# Container runtime selection (docker | podman)
#
# OWGE scripts historically assumed the Docker CLI. Podman (>= 4, with its
# Docker-compatible API) is a drop-in alternative: same compose files, same
# `docker`-flavored commands, driven by `docker-compose` (v2) or `podman quad`
# against the podman socket.
#
#   OWGE_RUNTIME=docker|podman  force a runtime (else auto-detected)
#   PODMAN_SOCKET               override the podman socket path
#
# Sourcing this file installs a `docker` wrapper at the front of PATH (a real
# file, so pipes and `xargs docker ...` reach it): every `docker ...` call in
# the sourcing script transparently dispatches to the chosen runtime binary.
#
# @author Kevin Guanche Darias
##
function owgeRuntime () {
        if [ -n "$OWGE_RUNTIME" ]; then
                echo "$OWGE_RUNTIME";
                return;
        fi
        # NB: a real docker CLI (if any) must be found with `type -P` (binary
        # only), since the installed wrapper shadows the `docker` name on PATH.
        if commandExists podman; then
                echo "podman";
        elif type -P docker &> /dev/null; then
                echo "docker";
        fi
}

##
# Pins the container runtime, bootstraps the podman API service when needed,
# and installs the `docker` wrapper on PATH (a real binary, so pipes and
# xargs can reach it too). Idempotent; safe to call more than once.
#
# @author Kevin Guanche Darias
##
function initContainerRuntime () {
        # Resolve the runtime (auto-detect unless OWGE_RUNTIME pins it), then
        # validate it and bootstrap any runtime-specific prerequisites.
        _OWGE_RUNTIME="${_OWGE_RUNTIME-$(owgeRuntime)}";
        case "$_OWGE_RUNTIME" in
                podman)
                        commandExists podman || { log error "podman not found, install it or set OWGE_RUNTIME=docker"; return 1; };
                        podmanSocketReady || return 1;
                        ;;
                docker|"")
                        _OWGE_RUNTIME="docker";
                        export _OWGE_RUNTIME;
                        type -P docker &> /dev/null || { log error "docker runtime selected but the docker CLI is not on PATH (set OWGE_RUNTIME=podman for podman)"; return 1; };
                        ;;
                *)
                        log error "OWGE_RUNTIME must be 'docker' or 'podman' (got: $_OWGE_RUNTIME)";
                        return 1;
                        ;;
        esac
        # The wrapper binary reads OWGE_RUNTIME (its generated dispatch keys
        # off it); mirror the resolved runtime there, not just in _OWGE_RUNTIME.
        export OWGE_RUNTIME="$_OWGE_RUNTIME";
        _installRuntimeWrapper;
        export _OWGE_RUNTIME;
}

##
# Installs a real `docker` binary at the front of PATH (not a shell function,
# so pipes and `xargs docker ...` in the sourcing script reach it). It is a
# thin dispatch to the runtime `initContainerRuntime` resolved, pinned in the
# exported OWGE_RUNTIME env var. The wrapper lives in a deterministic per-user
# dir (shared across re-sources and child processes) and is rewritten in
# place.
#
# @author Kevin Guanche Darias
##
function _installRuntimeWrapper () {
        # Deterministic per-user wrapper dir: re-sources and child processes
        # share it, so /tmp doesn't accumulate a dir per process. (The file
        # is small and its content depends only on the resolved docker path,
        # so overwriting is safe.)
        _owge_runtime_dir="${XDG_RUNTIME_DIR:-/tmp}/owge_runtime_$UID";
        mkdir -p "$_owge_runtime_dir" 2> /dev/null || _owge_runtime_dir="$(mktemp -d /tmp/owge_runtime_XXXXXX)";
        # The wrapper's docker case must exec the real CLI; capture its path.
        _owge_real_docker="$(type -P docker 2> /dev/null || true)";
        cat > "${_owge_runtime_dir}/docker" <<OWGE_DOCKER_WRAPPER
#!/bin/sh
# OWGE container-runtime wrapper (generated by lib.sh initContainerRuntime).
# Forwards to the runtime pinned in OWGE_RUNTIME (podman | docker).
case "\${OWGE_RUNTIME-podman}" in
	podman) exec podman "\$@" ;;
	docker) exec "${_owge_real_docker}" "\$@" ;;
esac
OWGE_DOCKER_WRAPPER
        chmod +x "${_owge_runtime_dir}/docker";
        export PATH="${_owge_runtime_dir}:$PATH";
}

##
# Ensures the podman Docker-compatible API is serving and exports DOCKER_HOST.
# Starts `podman system service` in a detached tmux session when the socket is
# absent. Returns 1 if the service could not be brought up.
#
# @env PODMAN_SOCKET override the socket path
# @author Kevin Guanche Darias
##
function podmanSocketReady () {
        _podmanSocket="${PODMAN_SOCKET:-${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/podman/podman.sock}";
        _serving="";
        if [ -S "$_podmanSocket" ] && { ! commandExists curl || curl -s --max-time 2 --unix-socket "$_podmanSocket" http://127.0.0.1/_ping 2>/dev/null | grep -q OK; }; then
                _serving=1;
        fi
        if [ -z "$_serving" ]; then
                commandExists tmux || { log error "Podman API is not running and tmux is not available to start it. Start it yourself: podman system service --time 0"; return 1; };
                log info "Starting podman API service in tmux session 'owge-podman-svc' (socket $_podmanSocket)";
                tmux new-session -d -s owge-podman-svc "podman system service --time 0";
                _i=0;
                while [ $_i -lt 10 ]; do
                        sleep 1;
                        if [ -S "$_podmanSocket" ] && { ! commandExists curl || curl -s --max-time 2 --unix-socket "$_podmanSocket" http://127.0.0.1/_ping 2>/dev/null | grep -q OK; }; then
                                _serving=1;
                                break;
                        fi
                        _i=$((_i + 1));
                done
                if [ -z "$_serving" ]; then
                        log error "Podman API did not answer on $_podmanSocket after 10s";
                        return 1;
                fi
        fi
        export DOCKER_HOST="unix://$_podmanSocket";
}

##
# Low-priority helpers, so a build doesn't starve the running universes.
#
# The heavy compilers (mvn, ng) run INSIDE docker containers, as children of the
# docker daemon, so they don't inherit the script's nice value. We therefore split
# the problem in two:
#   - lowerHostPriority: re-execs the script under nice/ionice, covering the
#     host-side work the script does directly (cp, rm, git, docker build context).
#   - dockerBuildPriorityArgs: cgroup weights to pass to the build `docker run`s,
#     which DO throttle the in-container compilers (only bite under contention,
#     full speed when the host is idle).
#
# Linux-only (no-ops elsewhere). Tunable via OWGE_NICE_LEVEL, OWGE_IONICE_CLASS,
# OWGE_DOCKER_CPU_SHARES, OWGE_DOCKER_BLKIO_WEIGHT (set the latter empty to skip it
# on kernels/storage drivers that reject --blkio-weight).
#
# @author Kevin Guanche Darias
##
function lowerHostPriority () {
        if [ -n "$OWGE_PRIORITY_LOWERED" ] || [ "`uname -s`" != "Linux" ]; then
                return 0;
        fi
        export OWGE_PRIORITY_LOWERED=1;
        _prio="";
        commandExists nice && _prio="nice -n ${OWGE_NICE_LEVEL-19}";
        commandExists ionice && _prio="$_prio ionice -c ${OWGE_IONICE_CLASS-3}";
        if [ -n "$_prio" ]; then
                >&2 echo -e "\e[36mRunning build under low host priority ($_prio)\e[39m";
                exec $_prio "$0" "$@";
        fi
}

##
# Echoes the docker cgroup weight flags for build containers (stdout only, so it
# can be captured straight into a `docker run` line). Empty on non-Linux.
#
# @author Kevin Guanche Darias
##
function dockerBuildPriorityArgs () {
        test "`uname -s`" = "Linux" || return 0;
        # Podman run has no --cpu-shares/--blkio-weight; only the docker daemon
        # honors these cgroup weights.
        case "${_OWGE_RUNTIME-}" in
                podman) return 0 ;;
        esac
        echo -n "--cpu-shares=${OWGE_DOCKER_CPU_SHARES-256}";
        if [ -n "${OWGE_DOCKER_BLKIO_WEIGHT-100}" ]; then
                echo -n " --blkio-weight=${OWGE_DOCKER_BLKIO_WEIGHT-100}";
        fi
}

