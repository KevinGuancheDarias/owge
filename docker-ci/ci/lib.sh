##
# Auto-wire the container runtime when sourced by a dev script (images_creation
# run/build helpers, the launcher, etc.) rather than executed. The dev flow
# wants podman when available; the deploy scripts stay on docker because they
# call pinDockerRuntime (which sets OWGE_RUNTIME=docker) before any docker call.
# Guarded so re-sourcing and the deploy-pin path don't fight.
#
# @author Kevin Guanche Darias
##
if [ -n "${BASH_SOURCE[0]-}" ] && [ -z "${_OWGE_RUNTIME-}" ] && [ -z "${OWGE_RUNTIME-}" ] && [ -z "$_owge_auto_init_done" ]; then
        _owge_auto_init_done=1;
        # Podman-host preference: only auto-switch to podman when no real
        # docker CLI is present, so deploy/CI machines (which have docker)
        # keep the real docker binary and the pinDockerRuntime default.
        if commandExists podman && [ -z "$(type -P docker 2> /dev/null)" ]; then
                _OWGE_RUNTIME="podman";
                export OWGE_RUNTIME="podman";
                podmanSocketReady 2> /dev/null || true;
                _installRuntimeWrapper;
        fi
        export _OWGE_RUNTIME;
fi
